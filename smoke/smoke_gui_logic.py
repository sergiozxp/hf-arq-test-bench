[tnc]
host = "127.0.0.1"
cmd_port = 8300
data_port = 8301
mycall = {_toml_str(values['mycall'])}
peer_call = {_toml_str(values['peer_call'])}
bw_command = {_toml_str(values['bw'])}
cmd_response_window_s = 2.0
connect_timeout_s = 180
listen_timeout_s = 900
