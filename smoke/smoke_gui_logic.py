MERCURY_TESTS = {
    "E0-1  16-byte payload": dict(phase="e0", tag="E0-1_16B", size=16, bw_when="before"),
    "E0-1  1 KiB payload": dict(phase="e0", tag="E0-1_1KiB", size=1024, bw_when="before"),
    "E0-1  10 KiB payload": dict(phase="e0", tag="E0-1_10KiB", size=10240, bw_when="before"),
    "E0-2  Variant V1: BW before connect": dict(phase="e0", tag="E0-2_V1", size=200, bw_when="before"),
    "E0-2  Variant V2: BW after connect": dict(phase="e0", tag="E0-2_V2", size=200, bw_when="after"),
    "E0-3  Same-session ACK (200 bytes)": dict(phase="e0", tag="E0-3_ACK", size=200, bw_when="before",
                                               ack=True),
    "H1  Formal 200-byte transfer": dict(phase="smoke", tag="H1-{n}", size=200, bw_when="before", repeat=True),
}
# E0-2 V3 ("receiver listens first") was removed in 0.2.0-alpha.2: every test
# already starts the receiver first, so V3 ran exactly the same steps as V1.
H1_TEST = "H1  Formal 200-byte transfer"
REPETITION_LABEL = "H1 repetition number (1–3):"
REPETITION_HINT = "Run H1 three times: 1, then 2, then 3. Use the same number on PC A and PC B."


TESTS = MERCURY_TESTS  # the same procedure for every modem

# The whole MS-1.0 sequence in its fixed order (0.2.0-alpha.3; E0-3 from alpha.4): one RUN per PC.
SEQUENCE_TEST = "ALL  Full sequence: the 9 tests in order (recommended)"
SEQUENCE = [
    ("E0-1  16-byte payload", 1),
    ("E0-1  1 KiB payload", 1),
    ("E0-1  10 KiB payload", 1),
    ("E0-2  Variant V1: BW before connect", 1),
    ("E0-2  Variant V2: BW after connect", 1),
    ("E0-3  Same-session ACK (200 bytes)", 1),
    (H1_TEST, 1),
    (H1_TEST, 2),
    (H1_TEST, 3),
]
SEQUENCE_GAP_S = 45
TEST_CHOICES = [SEQUENCE_TEST, *MERCURY_TESTS]
SEQUENCE_LABEL = f"Start at step (1–{len(SEQUENCE)}):"
SEQUENCE_HINT = ("Normally 1. Use a later step only to finish a stopped sequence; "
                 "use the same step on PC A and PC B.")


def is_sequence(test_name: str) -> bool:
    return test_name == SEQUENCE_TEST


def is_h1(test_name: str) -> bool:
    return bool(MERCURY_TESTS.get(test_name, {}).get("repeat"))


def test_tag(test_name: str, repetition: int) -> str:
    if is_sequence(test_name):
        return sequence_label(repetition)
    preset = MERCURY_TESTS[test_name]
    return preset["tag"].replace("{n}", str(repetition))


def sequence_tags() -> list[str]:
    return [test_tag(name, repetition) for name, repetition in SEQUENCE]


def sequence_label(start: int = 1) -> str:
    tags = sequence_tags()[start - 1:]
    return f"the full sequence, {len(tags)} test(s): " + ", ".join(tags)


def sequence_commands(role: str, start: int = 1, gap_s: float = SEQUENCE_GAP_S) -> list[list[str]]:
    mode = "send" if role == "A" else "listen"
    command = ["smoke_sequence.py", mode, "--from", str(start)]
    if mode == "send":
        command += ["--gap-s", f"{gap_s:g}"]
    return [command]


STEP_RE = re.compile(r"^=== STEP (\d+)/(\d+): (\S+)")


def sequence_step_from_line(line: str) -> tuple[int, int, str] | None:
    match = STEP_RE.match(line.strip())
    return (int(match.group(1)), int(match.group(2)), match.group(3)) if match else None


def mercury_commands(preset: dict, role: str, repeat: int) -> list[list[str]]:
    mode = "send" if role == "A" else "listen"
    tag = preset["tag"].replace("{n}", str(repeat))
    return [[
        "mercury_smoke_client.py", mode, "--tag", tag,
        "--phase", preset["phase"], "--payload-size", str(preset["size"]),
        "--bw-when", preset["bw_when"],
    ] + (["--ack"] if preset.get("ack") else [])]


def summarize(result: dict) -> tuple[str, str]:
    """Return an English GUI summary and one of green/red/orange/gray."""
    failures = "; ".join(result.get("failures") or [])
    if result.get("exception"):
        return "SCRIPT ERROR. Review the live log and result.json.", "red"
    if "pairs" in result and "counts" in result:
        return summarize_report(result)
    if "planned_steps" in result and "steps" in result:
        return summarize_sequence(result)
    tag = result.get("tag") or result.get("sender_tag") or ""
    prefix = f"[{tag}] " if tag else ""
    incomplete = result.get("incomplete_evidence") or []
    evidence_note = (
        " INCOMPLETE EVIDENCE: " + "; ".join(str(item) for item in incomplete)
        if incomplete else ""
    )
    protocol = result.get("protocol_warnings") or []
    protocol_note = f" {len(protocol)} protocol warning(s): review result.json." if protocol else ""
    mode = result.get("mode")
    if mode == "send":
        if result.get("sender_completed"):
            return (
                prefix + "SENDER: the ARQ session completed (BUFFER 0). Delivery is verified "
                "only after the cross-check." + evidence_note + protocol_note,
                "orange",
            )
        return f"{prefix}SENDER FAILED: {failures}", "red"
    if mode == "listen":
        if result.get("delivered_intact"):
            return (
                prefix + "RECEIVER: payload received and hash verified." + evidence_note + protocol_note,
                "orange" if incomplete or protocol else "green",
            )
        return f"{prefix}RECEIVER FAILED: {failures}", "red"
    if "sender_receiver_hash_matches" in result:
        outcome = result.get("outcome")
        if outcome == "passed":
            return prefix + "CROSS-CHECK PASSED: intact delivery and complete evidence.", "green"
        if outcome == "incomplete":
            return prefix + "CROSS-CHECK INCOMPLETE: delivery was verified but evidence is missing.", "orange"
        if outcome == "invalid_pair":
            return (prefix + "NOT THE SAME TEST: " + "; ".join(result.get("pair_mismatches") or [])
                    + ". This pair is not counted.", "red")
        if outcome == "procedure_fault":
            return (prefix + "PROCEDURE FAULT: the sender started before the receiver was listening. "
                    "Not counted; repeat this test, PC B first.", "orange")
        if outcome == "infrastructure_fault":
            return prefix + "INFRASTRUCTURE FAULT (for example MISSING SOUNDCARD): not counted.", "orange"
        return prefix + "CROSS-CHECK FAILED: " + "; ".join(result.get("warnings") or []), "red"
    if result.get("step") == "disconnect":
        return "Disconnect requested.", "orange"
    return f"STEP FAILED: {result.get('reason', failures)}", "red"


def summarize_sequence(report: dict) -> tuple[str, str]:
    """Summarise one PC's run of the full sequence."""
    side = "SENDER" if report.get("mode") == "send" else "RECEIVER"
    done, planned = report.get("completed_steps", 0), report.get("planned_steps", 0)
    if report.get("outcome") == "completed":
        note = (" Delivery is verified only by the cross-check." if side == "SENDER"
                else " Every payload hash verified.")
        return (f"SEQUENCE COMPLETED ({side}): {done} of {planned} test(s) passed on this PC.{note} "
                "Next: Create results ZIP on PC B and cross-check it on PC A.",
                "orange" if side == "SENDER" else "green")
    steps = report.get("steps") or []
    last = steps[-1]["tag"] if steps else "?"
    return (f"SEQUENCE STOPPED at {last} ({side}): {done} of {planned} test(s) passed before it. "
            "Keep both PCs' results; do not delete the failed run.", "red")


def summarize_report(report: dict) -> tuple[str, str]:
    """Summarise a session cross-check report (all pairs of one session)."""
    counts = report.get("counts") or {}
    parts = [f"{n} {outcome}" for outcome, n in sorted(counts.items())]
    text = f"SESSION CROSS-CHECK: {len(report.get('pairs') or [])} pair(s): " + (", ".join(parts) or "none")
    crossed = report.get("crossed_runs") or []
    unpaired = report.get("unpaired") or []
    if crossed:
        text += (f". {len(crossed)} CROSSED RUN(S): the PCs ran different tests at the same time ("
                 + "; ".join(f"{c['sender_tag']} / {c['receiver_tag']}" for c in crossed) + ")")
    if unpaired:
        text += f". {len(unpaired)} run(s) without a partner"
    if report.get("outcome") == "passed" and not unpaired:
        return text + ".", "green"
    bad = any(k in counts for k in ("failed", "invalid_pair"))
    return text + ". See the table in the log.", "red" if bad else "orange"


RESULT_PATH_RE = re.compile(r"(?:Result saved to:|Report saved to:|Sequence saved to:|->)\s*(.+\.json)\s*$")


def result_path_from_line(line: str) -> str | None:
    match = RESULT_PATH_RE.search(line.strip())
    return match.group(1).strip() if match else None


SCRIPTS = {
    "mercury_smoke_client.py": "mercury_smoke_client",
    "smoke_cross_check.py": "smoke_cross_check",
    "smoke_sequence.py": "smoke_sequence",
}


def run_script(name: str, args: list[str]) -> int:
    """Run a bundled script when the GUI has been packaged as an executable."""
    import importlib
    import os
    import sys

    if name not in SCRIPTS:
        print(f"Unknown script: {name}")
        return 2
    for stream_name in ("stdout", "stderr"):
        stream = getattr(sys, stream_name, None)
        if stream is None:
            setattr(sys, stream_name, open(os.devnull, "w", encoding="utf-8"))
        else:
            try:
                stream.reconfigure(encoding="utf-8", errors="replace")
            except (AttributeError, ValueError):
                pass
    module = importlib.import_module(SCRIPTS[name])
    old_argv = sys.argv
    try:
        sys.argv = [name, *args]
        return module.main()
    finally:
        sys.argv = old_argv
