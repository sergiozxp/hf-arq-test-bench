def is_h1(test_name: str) -> bool:
    return bool(MERCURY_TESTS.get(test_name, {}).get("repeat"))


def mercury_commands(preset: dict, role: str, repeat: int) -> list[list[str]]:
    mode = "send" if role == "A" else "listen"
    tag = preset["tag"].replace("{n}", str(repeat))
    return [[
        "mercury_smoke_client.py", mode, "--tag", tag,
        "--phase", preset["phase"], "--payload-size", str(preset["size"]),
        "--bw-when", preset["bw_when"],
    ]]


def summarize(result: dict) -> tuple[str, str]:
    """Return an English GUI summary and one of green/red/orange/gray."""
    failures = "; ".join(result.get("failures") or [])
    if result.get("exception"):
        return "SCRIPT ERROR. Review the live log and result.json.", "red"
    incomplete = result.get("incomplete_evidence") or []
    evidence_note = (
        " INCOMPLETE EVIDENCE: " + "; ".join(str(item) for item in incomplete)
        if incomplete else ""
    )
    mode = result.get("mode")
    if mode == "send":
        if result.get("sender_completed"):
            return (
                "SENDER: the ARQ session completed (BUFFER 0). Delivery is verified "
                "only after checking the receiver result." + evidence_note,
                "orange",
            )
        return f"SENDER FAILED: {failures}", "red"
    if mode == "listen":
        if result.get("delivered_intact"):
            return (
                "RECEIVER: payload received and hash verified." + evidence_note,
                "orange" if incomplete else "green",
            )
        return f"RECEIVER FAILED: {failures}", "red"
    if "sender_receiver_hash_matches" in result:
        outcome = result.get("outcome")
        if outcome == "passed":
            return "CROSS-CHECK PASSED: intact delivery and complete evidence.", "green"
        if outcome == "incomplete":
            return "CROSS-CHECK INCOMPLETE: delivery was verified but evidence is missing.", "orange"
        return "CROSS-CHECK FAILED: " + "; ".join(result.get("warnings") or []), "red"
    if result.get("step") == "disconnect":
        return "Disconnect requested.", "orange"
    return f"STEP FAILED: {result.get('reason', failures)}", "red"


RESULT_PATH_RE = re.compile(r"(?:Result saved to:|->)\s*(.+result\.json)\s*$")


def result_path_from_line(line: str) -> str | None:
    match = RESULT_PATH_RE.search(line.strip())
    return match.group(1).strip() if match else None


SCRIPTS = {
    "mercury_smoke_client.py": "mercury_smoke_client",
    "smoke_cross_check.py": "smoke_cross_check",
}


def run_script(name: str, args: list[str]) -> int:
    """Run a bundled script when the GUI has been packaged as an executable."""
    import importlib
    import os
    import sys

    if name not in SCRIPTS:
        print(f"Unknown script: {name}")
        return 2
    for stream_name in ("stdout", "stderr"):
        stream = getattr(sys, stream_name, None)
        if stream is None:
            setattr(sys, stream_name, open(os.devnull, "w", encoding="utf-8"))
        else:
            try:
                stream.reconfigure(encoding="utf-8", errors="replace")
            except (AttributeError, ValueError):
                pass
    module = importlib.import_module(SCRIPTS[name])
    old_argv = sys.argv
    try:
        sys.argv = [name, *args]
        return module.main()
    finally:
        sys.argv = old_argv
