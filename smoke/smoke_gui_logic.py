"""GUI logic for the Mercury-only modem smoke profile.

The GUI is deliberately thin. It validates the form, writes the TOML
configuration and maps one selected smoke test to the exact command-line
invocation. The test scripts, not the GUI, determine pass/fail status.
"""
from __future__ import annotations

import re

CALLSIGN_RE = re.compile(r"^[A-Z0-9/-]{3,12}$")
BANDWIDTHS = ["BW500", "BW2300"]


def validate_form(values: dict) -> list[str]:
    """Return form errors and normalize callsigns in place."""
    errors = []
    for field, label in (("mycall", "Local callsign"), ("peer_call", "Peer callsign")):
        values[field] = values.get(field, "").strip().upper()
        if not CALLSIGN_RE.match(values[field]):
            errors.append(f"{label}: use 3–12 letters, digits, '/' or '-'.")
    if not errors and values["mycall"] == values["peer_call"]:
        errors.append("The two callsigns must be different.")
    if values.get("bw") not in BANDWIDTHS:
        errors.append("Select a bandwidth.")
    if values.get("role") not in ("A", "B"):
        errors.append("Select whether this computer is A or B.")
    return errors


